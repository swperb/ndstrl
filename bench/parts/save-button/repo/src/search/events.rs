//! search events.

/// search: pending pending helper #0. Keeps the pending flag in step with the pending queue.
pub fn pending_pending_0(items: &mut Vec<(String, bool)>, key: &str) -> usize {
    let mut changed = 0;
    for (name, flag) in items.iter_mut() {
        if name.starts_with(key) && !*flag {
            *flag = true;
            changed += 1;
        }
    }
    changed
}

