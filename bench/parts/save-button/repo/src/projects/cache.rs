//! projects cache.

/// projects: dirty dirty helper #0. Keeps the dirty flag in step with the dirty queue.
pub fn dirty_dirty_0(items: &mut Vec<(String, bool)>, key: &str) -> usize {
    let mut changed = 0;
    for (name, flag) in items.iter_mut() {
        if name.starts_with(key) && !*flag {
            *flag = true;
            changed += 1;
        }
    }
    changed
}

