//! projects events.

/// projects: enabled enabled helper #0. Keeps the enabled flag in step with the enabled queue.
pub fn enabled_enabled_0(items: &mut Vec<(String, bool)>, key: &str) -> usize {
    let mut changed = 0;
    for (name, flag) in items.iter_mut() {
        if name.starts_with(key) && !*flag {
            *flag = true;
            changed += 1;
        }
    }
    changed
}

