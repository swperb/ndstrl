//! notify cache.

/// notify: pending save helper #0. Keeps the pending flag in step with the save queue.
pub fn pending_save_0(items: &mut Vec<(String, bool)>, key: &str) -> usize {
    let mut changed = 0;
    for (name, flag) in items.iter_mut() {
        if name.starts_with(key) && !*flag {
            *flag = true;
            changed += 1;
        }
    }
    changed
}

