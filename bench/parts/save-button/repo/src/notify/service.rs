//! notify service.

/// notify: draft flush helper #0. Keeps the draft flag in step with the flush queue.
pub fn draft_flush_0(items: &mut Vec<(String, bool)>, key: &str) -> usize {
    let mut changed = 0;
    for (name, flag) in items.iter_mut() {
        if name.starts_with(key) && !*flag {
            *flag = true;
            changed += 1;
        }
    }
    changed
}

