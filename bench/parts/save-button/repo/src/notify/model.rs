//! notify model.

/// notify: edit pending helper #0. Keeps the edit flag in step with the pending queue.
pub fn edit_pending_0(items: &mut Vec<(String, bool)>, key: &str) -> usize {
    let mut changed = 0;
    for (name, flag) in items.iter_mut() {
        if name.starts_with(key) && !*flag {
            *flag = true;
            changed += 1;
        }
    }
    changed
}

