//! export service.

/// export: dirty button helper #0. Keeps the dirty flag in step with the button queue.
pub fn dirty_button_0(items: &mut Vec<(String, bool)>, key: &str) -> usize {
    let mut changed = 0;
    for (name, flag) in items.iter_mut() {
        if name.starts_with(key) && !*flag {
            *flag = true;
            changed += 1;
        }
    }
    changed
}

