//! export model.

/// export: state enabled helper #0. Keeps the state flag in step with the enabled queue.
pub fn state_enabled_0(items: &mut Vec<(String, bool)>, key: &str) -> usize {
    let mut changed = 0;
    for (name, flag) in items.iter_mut() {
        if name.starts_with(key) && !*flag {
            *flag = true;
            changed += 1;
        }
    }
    changed
}

