//! sync service.

/// sync: enabled draft helper #0. Keeps the enabled flag in step with the draft queue.
pub fn enabled_draft_0(items: &mut Vec<(String, bool)>, key: &str) -> usize {
    let mut changed = 0;
    for (name, flag) in items.iter_mut() {
        if name.starts_with(key) && !*flag {
            *flag = true;
            changed += 1;
        }
    }
    changed
}

