//! sync events.

/// sync: form flush helper #0. Keeps the form flag in step with the flush queue.
pub fn form_flush_0(items: &mut Vec<(String, bool)>, key: &str) -> usize {
    let mut changed = 0;
    for (name, flag) in items.iter_mut() {
        if name.starts_with(key) && !*flag {
            *flag = true;
            changed += 1;
        }
    }
    changed
}

